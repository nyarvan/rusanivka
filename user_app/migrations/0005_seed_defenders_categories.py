def seed_defenders(apps: Any, schema_editor: Any) -> None:
    """Create defenders categories with one starter post each."""
    CategoryBlog = apps.get_model('user_app', 'CategoryBlog')
    Blog = apps.get_model('user_app', 'Blog')

    for slug, title, text in DEFENDERS_POSTS:
        category, _ = CategoryBlog.objects.get_or_create(
            slug=slug, defaults={'title': title})
        # Never add a starter post next to content written by a manager.
        if Blog.objects.filter(category=category).exists():
            continue
        # `category` is passed explicitly: the historical model would
        # otherwise call get_default_category() and require 'novini'.
        Blog.objects.create(
            category=category, title=title, slug=slug, text=text)


